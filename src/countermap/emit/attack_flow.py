"""Render a resolved scenario as a CTID Attack Flow 2.0 STIX bundle."""

from __future__ import annotations

import datetime as _dt
import hashlib
import json
import uuid
from typing import Any

from ..query import Countermap
from ..scenario import ResolvedScenario
from .validate import ATTACK_FLOW_EXTENSION_ID

CTID_IDENTITY = "identity--d673f8cb-c168-42da-8ed4-0cb26725f86c"
EXTENSION_DEFINITION = {
    "type": "extension-definition",
    "id": ATTACK_FLOW_EXTENSION_ID,
    "spec_version": "2.1",
    "name": "Attack Flow",
    "description": "Extends STIX 2.1 with features to create Attack Flows.",
    "created": "2022-08-02T19:34:35.143Z",
    "modified": "2022-08-02T19:34:35.143Z",
    "created_by_ref": CTID_IDENTITY,
    "schema": "https://center-for-threat-informed-defense.github.io/attack-flow/stix/attack-flow-schema-2.0.0.json",
    "version": "2.0.0",
    "extension_types": ["new-sdo"],
    "external_references": [
        {"source_name": "Documentation", "description": "Documentation for Attack Flow",
         "url": "https://center-for-threat-informed-defense.github.io/attack-flow"},
        {"source_name": "GitHub", "description": "Source code repository for Attack Flow",
         "url": "https://github.com/center-for-threat-informed-defense/attack-flow"},
    ],
}
CTID_IDENTITY_OBJECT = {
    "type": "identity", "spec_version": "2.1", "id": CTID_IDENTITY, "created_by_ref": CTID_IDENTITY,
    "created": "2022-08-02T19:34:35.143Z", "modified": "2022-08-02T19:34:35.143Z",
    "name": "MITRE Center for Threat-Informed Defense", "identity_class": "organization",
}
EXT = {ATTACK_FLOW_EXTENSION_ID: {"extension_type": "new-sdo"}}
NAMESPACE = uuid.UUID("6c1a8f0e-2f4b-4c1e-9d55-0a8a2a6d9f31")


def _id(kind: str, *parts: str) -> str:
    return f"{kind}--{uuid.uuid5(NAMESPACE, '|'.join(parts))}"


def render_attack_flow(rs: ResolvedScenario, c: Countermap, *, scope: str = "incident",
                       timestamp: str | None = None) -> dict[str, Any]:
    ts = timestamp or _dt.datetime.now(_dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.000Z")
    # IDs are stable for identical content and distinct for different flows that share a title.
    fp = hashlib.sha256(json.dumps(
        [rs.title, rs.description, [(s.id, s.node_id, s.after, s.description, s.assets) for s in rs.steps]],
        sort_keys=True).encode()).hexdigest()[:16]
    author = rs.authors[0] if rs.authors else "Countermap"
    author_id = _id("identity", "author", author)
    objects: list[dict[str, Any]] = [
        EXTENSION_DEFINITION,
        CTID_IDENTITY_OBJECT,
        {"type": "identity", "spec_version": "2.1", "id": author_id, "created_by_ref": author_id,
         "created": ts, "modified": ts, "name": author, "identity_class": "individual"},
    ]
    action_id = {s.id: _id("attack-action", fp, s.id) for s in rs.steps}
    successors: dict[str, list[str]] = {s.id: [] for s in rs.steps}
    for s in rs.steps:
        for prev in s.after:
            successors[prev].append(s.id)

    actions = []
    assets: dict[str, str] = {}
    for s in rs.steps:
        node = c._node(s.node_id)
        action: dict[str, Any] = {
            "type": "attack-action", "spec_version": "2.1", "id": action_id[s.id],
            "created": ts, "modified": ts, "name": s.label, "technique_id": s.technique_id,
            "extensions": EXT,
        }
        if node is not None and node["stix_id"] and node["stix_id"].startswith("attack-pattern--"):
            action["technique_ref"] = node["stix_id"]
        if s.tactics:
            tactic = c._node(s.tactics[0]["id"])
            action["tactic_id"] = tactic["ext_id"] if tactic else s.tactics[0]["id"]
            if tactic is not None and tactic["stix_id"]:
                action["tactic_ref"] = tactic["stix_id"]
        desc = s.description or ""
        if s.framework != "attack":
            desc = (desc + " " if desc else "") + f"[{s.framework.upper()} technique {s.technique_id}]"
        if desc:
            action["description"] = desc
        if successors[s.id]:
            action["effect_refs"] = [action_id[n] for n in successors[s.id]]
        refs = []
        for asset in s.assets:
            if asset not in assets:
                assets[asset] = _id("attack-asset", fp, asset)
            refs.append(assets[asset])
        if refs:
            action["asset_refs"] = refs
        actions.append(action)

    flow = {
        "type": "attack-flow", "spec_version": "2.1", "id": _id("attack-flow", fp),
        "created_by_ref": author_id, "created": ts, "modified": ts, "name": rs.title,
        "description": rs.description or "Generated by Countermap from MITRE knowledge bases.",
        "scope": scope,
        "start_refs": [action_id[s.id] for s in rs.steps if not s.after],
        "extensions": EXT,
    }
    objects.append(flow)
    objects.extend(actions)
    for name, asset_id in assets.items():
        objects.append({"type": "attack-asset", "spec_version": "2.1", "id": asset_id, "created": ts,
                        "modified": ts, "name": name, "extensions": EXT})
    return {"type": "bundle", "id": _id("bundle", fp, ts), "objects": objects}
