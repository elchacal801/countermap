"""ATT&CK Navigator layers (layer format 4.5), including F3 layers for the F3 Navigator domain."""

from __future__ import annotations

from typing import Any

from ..query import Countermap, NotFound

NAVIGATOR_VERSION = "5.3.1"
LAYER_VERSION = "4.5"
F3_DOMAIN = "f3-financial"
F3_DATA_URL = "https://raw.githubusercontent.com/center-for-threat-informed-defense/fight-fraud-framework/refs/heads/main/public/f3-stix.json"


def f3_data_url(loaded_url: str | None) -> tuple[str, str | None]:
    """The F3 bundle an F3 layer should load: the file the database was built from, if a browser can fetch it.

    Otherwise (a local file or plain http) the layer falls back to F3's moving latest file, with a note.
    """
    if loaded_url and loaded_url.startswith("https://"):
        return loaded_url, None
    return F3_DATA_URL, ("F3 was not loaded from an https URL, so the F3 layer's customDataURL points at F3's latest "
                         "release, which may differ from the loaded data")


def navigator_layers(c: Countermap, refs: list[str], *, name: str, description: str = "",
                     scores: dict[str, float] | None = None, comments: dict[str, str] | None = None,
                     color: str | None = None,
                     metadata: dict[str, list[dict[str, str]]] | None = None) -> dict[str, Any]:
    """Build one layer per domain from technique references. Unknown IDs are reported, never dropped silently.

    ``metadata`` maps a reference to Navigator metadata items ({"name", "value"}) shown in the technique's tooltip.
    """
    versions = c.source_versions()
    per_domain: dict[str, dict[str, dict[str, Any]]] = {}
    warnings: list[str] = []
    for ref in refs:
        try:
            node_id, notes = c._ref_resolved(ref)
        except NotFound as exc:
            warnings.append(str(exc))
            continue
        warnings.extend(notes)
        row = c._node(node_id)
        if row["kind"] != "technique" or row["framework"] not in ("attack", "f3"):
            warnings.append(f"{node_id} cannot be placed on a Navigator layer ({row['framework']} {row['kind']})")
            continue
        domains = [d for d in (c.lookup(node_id, desc_chars=0)["domains"] or [])]
        domain = F3_DOMAIN if row["framework"] == "f3" else (domains[0] if domains else "enterprise-attack")
        entries = per_domain.setdefault(domain, {})
        tid = row["ext_id"]
        entry = entries.setdefault(tid, {"techniqueID": tid, "enabled": True, "metadata": [], "links": [],
                                         "showSubtechniques": False, "comment": "", "color": color or ""})
        key_score = (scores or {}).get(ref, (scores or {}).get(tid))
        entry["score"] = key_score if key_score is not None else entry.get("score", 1)
        if comments and (comments.get(ref) or comments.get(tid)):
            entry["comment"] = comments.get(ref) or comments.get(tid)
        for item in (metadata or {}).get(ref, []):
            if item not in entry["metadata"]:
                entry["metadata"].append(item)
        if "." in tid:
            parent = tid.split(".")[0]
            entries.setdefault(parent, {"techniqueID": parent, "enabled": True, "metadata": [], "links": [],
                                        "comment": "", "color": ""})["showSubtechniques"] = True
    f3_url = None
    if F3_DOMAIN in per_domain:
        loaded = next((s["url"] for s in c.datasets()["sources"] if s["key"] == "f3" and s["status"] == "loaded"), None)
        f3_url, note = f3_data_url(loaded)
        if note:
            warnings.append(note)
    layers = {}
    for domain, entries in per_domain.items():
        scored = [e["score"] for e in entries.values() if "score" in e]
        layer: dict[str, Any] = {
            "name": name,
            "versions": {
                "attack": str(versions.get("attack-enterprise") or "").split(".")[0] if domain != F3_DOMAIN else "17",
                "navigator": NAVIGATOR_VERSION,
                "layer": LAYER_VERSION,
            },
            "domain": domain,
            "description": description or "Generated by Countermap",
            "sorting": 0,
            "layout": {"layout": "side", "showID": True, "showName": True, "expandedSubtechniques": "annotated"},
            "hideDisabled": False,
            "techniques": list(entries.values()),
            "gradient": {"colors": ["#ffe766ff", "#ff6666ff"], "minValue": 0, "maxValue": max(scored, default=1)},
            "legendItems": [],
            "metadata": [{"name": "generated_by", "value": "Countermap"}],
            "links": [],
            "showTacticRowBackground": False,
            "tacticRowBackground": "#dddddd",
            "selectTechniquesAcrossTactics": True,
            "selectSubtechniquesWithParent": False,
            "selectVisibleTechniques": False,
        }
        if domain == F3_DOMAIN:
            # Mirrors the layer MITRE CTID publishes for F3 (f3-navigator.json), but pinned to the loaded release.
            layer["customDataURL"] = f3_url
            layer["filters"] = {"platforms": ["F3"]}
            layer["metadata"].append({"name": "f3_stix_version", "value": str(versions.get("f3") or "")})
        layers[domain] = layer
    return {"layers": layers, "warnings": warnings}


COVERAGE_COLORS = {0: "#ff6666ff", 1: "#ffe766ff", 2: "#8ec843ff"}


def coverage_layers(c: Countermap, refs: list[str], *, name: str, description: str, scores: dict[str, int],
                    comments: dict[str, str], labels: dict[int, str]) -> dict[str, Any]:
    """Layers that score each technique 2, 1 or 0 (for example covered, partial, blind), with a fixed legend.

    ``scores`` and ``comments`` are keyed by ATT&CK ID. A technique without a score (for example one with no
    detection strategy) is placed on the layer with its comment but left unscored, so it is not colored.
    """
    nav = navigator_layers(c, refs, name=name, description=description, scores=scores, comments=comments)
    for layer in nav["layers"].values():
        for entry in layer["techniques"]:
            if entry["techniqueID"] not in scores:
                entry.pop("score", None)
        layer["gradient"] = {"colors": [COVERAGE_COLORS[0], COVERAGE_COLORS[1], COVERAGE_COLORS[2]],
                             "minValue": 0, "maxValue": 2}
        layer["legendItems"] = [{"label": f"{labels[s]} ({s})", "color": COVERAGE_COLORS[s]} for s in (2, 1, 0)]
    return nav
